"""Compile wml-metadata.json into flat C++ tables.

The JSON is produced by tools/schema-gen/DumpSdkMetadata, which reads the
schema metadata that DocumentFormat.OpenXml uses at run time. This script is
an offline development step; its output is committed so that building and
testing doccraft never needs .NET.

Usage:
  python3 tools/schema-gen/gen_wml_schema.py \
      tools/schema-gen/wml-metadata.json src/ooxml/generated
"""

import json
import pathlib
import sys

KIND = {
    "Sequence": "kSequence",
    "Choice": "kChoice",
    "Group": "kGroup",
    "All": "kAll",
    "Element": "kElement",
    "Any": "kAny",
}

# SDK attribute scalar types mapped to validator check kinds. kOnOff, the
# integer widths and the two binary types carry a lexical check; kString,
# kEnum and kDateTime are recorded distinctly (unknown-attribute detection
# still applies) but their value spaces are not validated yet: EnumValue
# needs the member table and DateTimeValue accepts many formats.
ATTRIBUTE_TYPE = {
    "StringValue": "kString",
    "OnOffValue": "kOnOff",
    "EnumValue`1": "kEnum",
    "DateTimeValue": "kDateTime",
    "Int16Value": "kInt16",
    "Int32Value": "kInt32",
    "Int64Value": "kInt64",
    "IntegerValue": "kInteger",
    "UInt16Value": "kUInt16",
    "UInt32Value": "kUInt32",
    "ByteValue": "kByte",
    "HexBinaryValue": "kHexBinary",
    "Base64BinaryValue": "kBase64Binary",
    "TrueFalseValue": "kOther",
    "TrueFalseBlankValue": "kOther",
    "BooleanValue": "kOther",
    "SingleValue": "kOther",
    "DecimalValue": "kOther",
}

