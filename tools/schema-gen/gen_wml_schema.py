"""Compile wml-metadata.json into flat C++ tables.

The JSON is produced by tools/schema-gen/DumpSdkMetadata, which reads the
schema metadata that DocumentFormat.OpenXml uses at run time. This script is
an offline development step; its output is committed so that building and
testing doccraft never needs .NET.

Usage:
  python3 tools/schema-gen/gen_wml_schema.py \
      tools/schema-gen/wml-metadata.json src/ooxml/generated
"""

import json
import pathlib
import sys

KIND = {
    "Sequence": "kSequence",
    "Choice": "kChoice",
    "Group": "kGroup",
    "All": "kAll",
    "Element": "kElement",
    "Any": "kAny",
}

