#ifndef SRC_BASE_UTF8_H_
#define SRC_BASE_UTF8_H_

#include <cstdint>
#include <string>

namespace doccraft::base {

// Appends one Unicode code point as UTF-8.
//
// Shared by the CFB directory-name decoder ([MS-CFB] §2.6.1 stores names as
// UTF-16LE) and the [MS-DOC] text plane, so the encoding exists once. This is
// pure encoding: replacement policy for code points that UTF-8 can carry but
// XML 1.0 cannot belongs to the caller (`doc::detail::ReadChars`).
inline void AppendUtf8(std::string& out, uint32_t cp) {
  if (cp < 0x80) {
    out += static_cast<char>(cp);
  } else if (cp < 0x800) {
    out += static_cast<char>(0xC0 | (cp >> 6));
    out += static_cast<char>(0x80 | (cp & 0x3F));
  } else if (cp < 0x10000) {
    out += static_cast<char>(0xE0 | (cp >> 12));
    out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
    out += static_cast<char>(0x80 | (cp & 0x3F));
  } else {
    out += static_cast<char>(0xF0 | (cp >> 18));
    out += static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
    out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
    out += static_cast<char>(0x80 | (cp & 0x3F));
  }
}

}  // namespace doccraft::base

#endif  // SRC_BASE_UTF8_H_
